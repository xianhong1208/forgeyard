def test_fy_kbk_005_an_admin_downloads_it_not_cached_audited_and_the_reminder_is_done(owner, caplog):
    """FY-KBK-005: an admin with their password and a passphrase gets the file as an attachment named
    after the key id and the date, with Cache-Control: no-store; it opens with that passphrase and
    holds the server's key and CA. The download is audited (key id, CA, file name; never the
    passphrase or the password), and the setup advisor's "Back up the secret key" is done for that key
    id. Nothing is kept on the server."""
    make_ca()
    caplog.set_level(logging.DEBUG)
    kid = crypto.box().kid
    assert any(f["id"] == "secret-key-backup" for f in owner.get("/api/advisor").json()["findings"])
    info = owner.get("/api/secret-key").json()
    assert info["kid"] == kid and info["includes_ca"] is True and info["backed_up"] is None and info["source"] == "file"
    before = sorted(p.name for p in get_settings().data_dir.rglob("*"))
    r = owner.post(URL, json=body())
    assert r.status_code == 200, r.text
    assert r.headers["cache-control"] == "no-store"
    assert r.headers["content-type"] == "application/octet-stream"
    assert re.fullmatch(rf'attachment; filename="forgeyard-key-backup-{kid}-\d{{8}}\.fykey"', r.headers["content-disposition"])
    got = keybackup.open_backup(r.content, PASS)
    assert got.key == crypto.load_key(create=False) and got.kid == kid
    assert got.tls == {f: (get_settings().tls_dir / f).read_text() for f in ("ca.key", "ca.crt")}
    rows = audit("secret_key.backup_downloaded")
    assert len(rows) == 1 and rows[0][0] == OWNER[0]
    assert rows[0][1]["kid"] == kid and rows[0][1]["includes_ca"] is True and rows[0][1]["file"].endswith(".fykey")
    everything = json.dumps([e for a in ("secret_key.backup_downloaded",) for e in audit(a)]) + caplog.text
    assert PASS not in everything and OWNER[1] not in everything
    assert all(f["id"] != "secret-key-backup" for f in owner.get("/api/advisor").json()["findings"])
    db = new_session()
    try:
        row = db.get(ServerSetting, "secret_key_backup")
        assert row.value["kid"] == kid and row.value["by"] == OWNER[0] and row.value["how"] == "download"
        assert PASS not in json.dumps([s.value for s in db.scalars(select(ServerSetting))], default=str)
    finally:
        db.close()
    assert sorted(p.name for p in get_settings().data_dir.rglob("*")) == before  # no file left behind
    assert owner.get("/api/secret-key").json()["backed_up"]["kid"] == kid


def test_fy_kbk_006_passphrase_problems_are_refused_and_not_counted_as_wrong_passwords(owner):
    """FY-KBK-006: a short passphrase, two different ones, or the password itself as passphrase: 422,
    no file, no back-off, the reminder stays."""
    for b, code in ((body(passphrase="short-one"), "weak_passphrase"), (body(confirm=PASS + "!"), "passphrase_mismatch"),
                    (body(passphrase=OWNER[1]), "passphrase_is_password")):
        r = owner.post(URL, json=b)
        assert r.status_code == 422 and r.json()["detail"]["code"] == code, r.text
    assert limiter.login_wait(OWNER[0], "testclient", 1, 1) == 0
    assert audit("secret_key.backup_downloaded") == [] and audit("secret_key.backup_failed") == []
    assert any(f["id"] == "secret-key-backup" for f in owner.get("/api/advisor").json()["findings"])


def test_fy_kbk_007_admins_only(owner):
    """FY-KBK-007: operators and users get 403 (both endpoints) even with their right password; no
    session gets 401; an admin without a password is told why (409)."""
    for role, name in (("operator", "otto"), ("user", "ursula")):
        add_user(owner, name, role=role)
        c = sign_in(owner, name, "quiet-meadow-4821")
        assert c.post(URL, json=body(password="quiet-meadow-4821")).status_code == 403
        assert c.get("/api/secret-key").status_code == 403
    with make_client() as anon:
        r = anon.post(URL, json=body())
        assert r.status_code == 401 and r.json()["detail"]["code"] == "not_signed_in"
    r = owner.post("/api/users", json={"username": "nopass", "role": "admin"})
    assert r.status_code == 201
    db = new_session()
    try:
        u = db.scalar(select(User).where(User.username == "nopass"))
        assert u.password_hash is None
        token, _ = sessions.create(db, u, "127.0.0.1", "test")
        db.commit()
    finally:
        db.close()
    with make_client() as c:
        c.cookies.set(sessions.COOKIE, token)
        r = c.post(URL, json=body(password="anything-at-all"))
        assert r.status_code == 409 and r.json()["detail"]["code"] == "no_password"
        assert c.get("/api/secret-key").json()["has_password"] is False
    assert audit("secret_key.backup_downloaded") == []


def test_fy_kbk_008_a_wrong_password_is_audited_and_backs_off_like_a_sign_in(owner):
    """FY-KBK-008: a wrong password answers 401 wrong_password (not an ended session: the session
    still works), is audited as secret_key.backup_failed, and counts as a failed sign-in of that
    account: after the free failures even the right password must wait (429 with Retry-After), and
    so must a sign-in."""
    free = get_settings().login_free_failures
    for _ in range(free):
        r = owner.post(URL, json=body(password="not-the-password-1"))
        assert r.status_code == 401 and r.json()["detail"]["code"] == "wrong_password", r.text
    assert owner.get("/api/auth/me").status_code == 200
    rows = audit("secret_key.backup_failed")
    assert len(rows) == free and all(d == {"reason": "wrong_password"} for _, d in rows)
    r = owner.post(URL, json=body())
    assert r.status_code == 429 and int(r.headers["retry-after"]) >= 1
    with make_client() as other:
        assert other.post("/api/auth/login", json={"username": OWNER[0], "password": OWNER[1]}).status_code == 429
    assert audit("secret_key.backup_downloaded") == []


def test_fy_kbk_009_cross_site_requests_are_refused(owner):
    """FY-KBK-009: without the X-Forgeyard header, or from another origin: 403 csrf, no file."""
    r = owner.post(URL, json=body(), headers={"X-Forgeyard": ""})
    assert r.status_code == 403 and r.json()["detail"]["code"] == "csrf"
    r = owner.post(URL, json=body(), headers={"Origin": "https://evil.example"})
    assert r.status_code == 403 and r.json()["detail"]["code"] == "csrf"
    assert audit("secret_key.backup_downloaded") == []


# ------------------------------------------------------------------ restore
def _restore(*args, passphrase=PASS, tmp_path):
    pf = tmp_path / "pass.txt"
    pf.write_text(passphrase + "\n")
    return cli.main(["secrets", "restore", *map(str, args), "--passphrase-file", str(pf)])


def test_fy_kbk_010_restore_into_a_fresh_data_dir_and_the_secrets_open_again(owner, tmp_path, monkeypatch):
    """FY-KBK-010: a downloaded backup restored with `secrets restore --data-dir` into an empty
    directory writes secret.key (0600) and tls/ca.key (0600), tls/ca.crt, tls/ (0700); a copy of the
    database next to it passes the startup key check, and a secret stored before opens with the
    restored key. The server then makes its server certificate from the restored CA."""
    make_ca()
    sealed = crypto.seal("provider-key-before-restore", "providers.api_key")
    kid = crypto.box().kid
    ca_before = (get_settings().tls_dir / "ca.crt").read_bytes()
    r = owner.post(URL, json=body())
    backup = tmp_path / "backup.fykey"
    backup.write_bytes(r.content)
    fresh = tmp_path / "fresh"
    import sqlite3

    fresh.mkdir()
    src = sqlite3.connect(get_settings().data_dir / "forgeyard.db")
    dst = sqlite3.connect(fresh / "forgeyard.db")
    src.backup(dst)
    src.close()
    dst.close()
    assert _restore(backup, "--data-dir", fresh, tmp_path=tmp_path) == 0
    assert stat.S_IMODE((fresh / "secret.key").stat().st_mode) == 0o600
    assert stat.S_IMODE((fresh / "tls").stat().st_mode) == 0o700
    assert stat.S_IMODE((fresh / "tls" / "ca.key").stat().st_mode) == 0o600
    assert (fresh / "tls" / "ca.crt").read_bytes() == ca_before
    monkeypatch.setenv("DATA_DIR", str(fresh))
    get_settings.cache_clear()
    reset_engine()
    crypto.reset()
    from forgeyard.db import get_engine

    with get_engine().connect() as conn:
        crypto.check_database(conn)  # raises on a wrong or missing key
    assert crypto.box().kid == kid
    assert crypto.unseal(sealed, "providers.api_key") == "provider-key-before-restore"
    material = tls.ensure()
    assert tls.read_cert(material.cert_file.read_bytes()).issuer == tls.read_cert(ca_before).subject


def test_fy_kbk_011_restore_never_overwrites_a_different_key_or_ca_without_force(owner, tmp_path):
    """FY-KBK-011: a different secret.key or CA already there stops restore (exit 2, nothing written);
    --force keeps them as <name>.replaced-<time> and writes the backup's; the same key already there
    is fine; a wrong passphrase or a damaged file writes nothing at all."""
    make_ca()
    r = owner.post(URL, json=body())
    backup = tmp_path / "b.fykey"
    backup.write_bytes(r.content)
    target = tmp_path / "other"
    (target / "tls").mkdir(parents=True)
    other_key = base64.urlsafe_b64encode(b"\x07" * 32).decode() + "\n"
    (target / "secret.key").write_text(other_key)
    assert _restore(backup, "--data-dir", target, tmp_path=tmp_path) == 2
    assert (target / "secret.key").read_text() == other_key
    assert not (target / "tls" / "ca.key").exists()
    # A different CA alone also stops it.
    tls.make_ca(target / "tls")
    their_ca = (target / "tls" / "ca.key").read_bytes()
    (target / "secret.key").write_text(base64.urlsafe_b64encode(crypto.load_key(create=False)).decode() + "\n")
    assert _restore(backup, "--data-dir", target, tmp_path=tmp_path) == 2
    assert (target / "tls" / "ca.key").read_bytes() == their_ca
    (target / "secret.key").write_text(other_key)
    assert _restore(backup, "--data-dir", target, "--force", tmp_path=tmp_path) == 0
    assert crypto._decode_key((target / "secret.key").read_text(), "x") == crypto.load_key(create=False)
    kept = sorted(p.name.split(".replaced-")[0] for p in target.rglob("*.replaced-*"))
    assert kept == ["ca.crt", "ca.key", "secret.key"]
    assert next(target.glob("secret.key.replaced-*")).read_text() == other_key
    # Again: everything is already there, nothing replaced.
    assert _restore(backup, "--data-dir", target, tmp_path=tmp_path) == 0
    assert len(list(target.rglob("*.replaced-*"))) == 3
    empty = tmp_path / "empty"
    assert _restore(backup, "--data-dir", empty, passphrase="wrong-passphrase-0", tmp_path=tmp_path) == 2
    damaged = tmp_path / "damaged.fykey"
    damaged.write_bytes(r.content[:-3])
    assert _restore(damaged, "--data-dir", empty, tmp_path=tmp_path) == 2
    assert not empty.exists()


def test_fy_kbk_012_a_key_from_the_environment_is_backed_up_and_a_server_without_its_own_ca_says_so(owner, monkeypatch):
    """FY-KBK-012: with FORGEYARD_SECRET_KEY the backup holds that key; with TLS off (or an own
    certificate) there is no Forgeyard CA in it, and GET /api/secret-key says so."""
    key = crypto.load_key(create=False)
    monkeypatch.setenv(crypto.KEY_ENV, base64.urlsafe_b64encode(key).decode())
    monkeypatch.setenv("TLS", "off")
    get_settings.cache_clear()
    make_ca()  # files there, but not used: not in the backup
    info = owner.get("/api/secret-key").json()
    assert info["source"] == "env" and info["includes_ca"] is False and info["tls_mode"] == "off"
    r = owner.post(URL, json=body())
    got = keybackup.open_backup(r.content, PASS)
    assert got.key == key and got.tls is None


def test_fy_kbk_013_contents_that_do_not_belong_together_are_refused(tmp_path, owner):
    """FY-KBK-013: even with the right passphrase, a key that does not match its key id, or a CA key
    that does not belong to the CA certificate, is refused; and a key file changed under a running
    server is not backed up (409: it is not the key the server runs with)."""
    c = sample()
    wrong_kid = keybackup.Contents(kid="00000000", key=c.key, tls=None, created_at="")
    with pytest.raises(keybackup.BackupError, match="does not match its key id"):
        keybackup.open_backup(keybackup.seal(wrong_kid, PASS), PASS)
    tls.make_ca(tmp_path / "other")
    mixed = keybackup.Contents(kid=c.kid, key=c.key, created_at="",
                               tls={"ca.key": (tmp_path / "other" / "ca.key").read_text(), "ca.crt": c.tls["ca.crt"]})
    with pytest.raises(keybackup.BackupError, match="do not belong together"):
        keybackup.open_backup(keybackup.seal(mixed, PASS), PASS)
    crypto.box()
    get_settings().secret_key_path.write_text(base64.urlsafe_b64encode(b"\x05" * 32).decode() + "\n")
    r = owner.get("/api/secret-key")
    assert r.status_code == 409 and r.json()["detail"]["code"] == "no_key"
    assert owner.post(URL, json=body()).status_code == 409
