PASS = "copper-kettle-moon-river"
URL = "/api/secret-key/backup"


def body(password=OWNER[1], passphrase=PASS, confirm=None):
    return {"password": password, "passphrase": passphrase, "passphrase_confirm": passphrase if confirm is None else confirm}


def make_ca():
    tls.make_ca(get_settings().tls_dir)


def audit(action):
    db = new_session()
    try:
        return [(e.actor_name, e.detail) for e in db.scalars(select(AuditEvent).where(AuditEvent.action == action))]
    finally:
        db.close()


def sample(with_ca=True):
    crypto.load_key(create=True)
    if with_ca:
        make_ca()
    return keybackup.current()


# ------------------------------------------------------------------ the format
def test_fy_kbk_001_round_trip_documented_header_and_fresh_salt_and_nonce():
    """FY-KBK-001: a sealed backup opens with its passphrase and gives back the same key and CA; the
    header names the format, version 1, Argon2id with its parameters and AES-256-GCM; every file gets
    its own salt and nonce; the passphrase is NFC-normalised (the same text typed on another system)."""
    c = sample()
    assert c.tls is not None and set(c.tls) == {"ca.key", "ca.crt"}
    data = keybackup.seal(c, PASS)
    assert data[:8] == b"FYKEYBK\0"
    (n,) = struct.unpack(">H", data[8:10])
    header = json.loads(data[10:10 + n])
    assert header["format"] == "forgeyard-key-backup" and header["version"] == 1 and header["kid"] == c.kid
    assert {k: v for k, v in header["kdf"].items() if k != "salt"} == {"name": "argon2id", "memory_kib": 65536,
                                                                     "iterations": 3, "lanes": 4}
    assert header["cipher"]["name"] == "aes-256-gcm"
    assert len(base64.b64decode(header["kdf"]["salt"])) == 16 and len(base64.b64decode(header["cipher"]["nonce"])) == 12
    assert c.key not in data and base64.urlsafe_b64encode(c.key) not in data and b"PRIVATE KEY" not in data
    back = keybackup.open_backup(data, PASS)
    assert (back.kid, back.key, back.tls) == (c.kid, c.key, c.tls)
    again = json.loads(keybackup.seal(c, PASS)[10:10 + n])
    assert again["kdf"]["salt"] != header["kdf"]["salt"] and again["cipher"]["nonce"] != header["cipher"]["nonce"]
    composed = "café-backup-phrase"            # é as one code point
    decomposed = "café-backup-phrase"    # e + combining accent
    assert keybackup.open_backup(keybackup.seal(c, composed), decomposed).key == c.key
    no_ca = keybackup.Contents(kid=c.kid, key=c.key, tls=None, created_at="")
    assert keybackup.open_backup(keybackup.seal(no_ca, PASS), PASS).tls is None


def test_fy_kbk_002_wrong_passphrase_a_changed_byte_and_a_cut_off_file_are_refused():
    """FY-KBK-002: a wrong passphrase, one changed byte anywhere (header, ciphertext, tag), a byte
    added, and a file cut off at any length are all refused."""
    data = keybackup.seal(sample(with_ca=False), PASS)
    assert keybackup.open_backup(data, PASS).kid == crypto.box().kid
    with pytest.raises(keybackup.BackupError, match="Wrong passphrase"):
        keybackup.open_backup(data, PASS + "x")
    (n,) = struct.unpack(">H", data[8:10])
    kid_at = data.index(b'"kid":"') + 8
    date_at = data.index(b'"created_at":"') + 15  # a header byte nothing else checks
    for at in (kid_at, date_at, 10 + n + 3, len(data) - 1):  # the header, the ciphertext, the tag
        bad = bytearray(data)
        bad[at] ^= 0x01
        with pytest.raises(keybackup.BackupError):
            keybackup.open_backup(bytes(bad), PASS)
    with pytest.raises(keybackup.BackupError, match="Wrong passphrase"):
        keybackup.open_backup(data + b"\0", PASS)
    for cut in (0, 5, 9, 12, 10 + n, 10 + n + 16, len(data) - 1):
        with pytest.raises(keybackup.BackupError):
            keybackup.open_backup(data[:cut], PASS)
    for cut in (10 + n, 10 + n + 16):  # the header is whole, the contents are not: said so
        with pytest.raises(keybackup.BackupError, match="cut off"):
            keybackup.open_backup(data[:cut], PASS)


def _with_header(data: bytes, change) -> bytes:
    (n,) = struct.unpack(">H", data[8:10])
    header = json.loads(data[10:10 + n])
    change(header)
    raw = json.dumps(header).encode()
    return data[:8] + struct.pack(">H", len(raw)) + raw + data[10 + n:]


def test_fy_kbk_003_unknown_version_format_or_parameters_are_refused_before_any_work(monkeypatch):
    """FY-KBK-003: another version, another format or cipher, a KDF other than argon2id, and
    parameters outside the accepted range (weaker, or large enough to exhaust memory) are refused by
    the header check, before the passphrase is ever derived."""
    data = keybackup.seal(sample(with_ca=False), PASS)
    derived = []
    monkeypatch.setattr(keybackup, "_derive", lambda *a: derived.append(a) or b"\0" * 32)
    cases = [
        (lambda h: h.update(version=2), "format version 2"),
        (lambda h: h.update(format="other"), "another format"),
        (lambda h: h["kdf"].update(name="scrypt"), "key derivation"),
        (lambda h: h["cipher"].update(name="chacha20"), "cipher"),
        (lambda h: h["kdf"].update(memory_kib=8 * 1024 * 1024), "memory_kib"),
        (lambda h: h["kdf"].update(memory_kib=1024), "memory_kib"),
        (lambda h: h["kdf"].update(iterations=1), "iterations"),
        (lambda h: h["kdf"].update(lanes=0), "lanes"),
        (lambda h: h["kdf"].update(salt="AAAA"), "salt"),
        (lambda h: h["cipher"].update(nonce="!!"), "nonce"),
    ]
    for change, words in cases:
        with pytest.raises(keybackup.BackupError, match=words):
            keybackup.open_backup(_with_header(data, change), PASS)
    for junk in (b"PK\x03\x04" + data[4:], b"", data[:8] + b"\xff\xff" + data[10:]):
        with pytest.raises(keybackup.BackupError):
            keybackup.open_backup(junk, PASS)
    assert derived == []


def test_fy_kbk_004_passphrase_rules():
    """FY-KBK-004: at least 12 characters, at most 1024, more than two different characters."""
    assert keybackup.passphrase_problem("a" * 11 + "b") is not None  # two different characters
    assert "12" in keybackup.passphrase_problem("short-pass1")
    assert keybackup.passphrase_problem("x" * 1025) is not None
    assert keybackup.passphrase_problem("abc-defg-hij") is None
    with pytest.raises(ValueError):
        keybackup.seal(sample(with_ca=False), "short")


