"""Pin the built-in recipes' engine images by digest, and record the ids a loaded copy can show.

Every container variant in forgeyard/recipes/*.yaml names its image as `repo:tag@sha256:…`: the
tag says which release it is (and is what the web UI shows), the digest is what the agent pulls,
so a tag moved on the registry can never change what runs.

    uv run --no-sync python scripts/pin_images.py           # check (exits 1 on any problem)
    uv run --no-sync python scripts/pin_images.py --write   # resolve each tag again, rewrite the YAML and the lock

Check: every tag still resolves to its pinned digest, and forgeyard/recipes/images.lock.json holds,
for each pinned image and nothing else, exactly what the registry serves for that digest now.

The lock records per image the ids a correct copy can show once loaded with `docker load` on a
machine that cannot reach the registry (see forgeyard/workloads/images.py): the index digest, and
per platform the manifest digest, the config digest and a content id (layers + run configuration).
It is a separate, generated file rather than a field per variant so the recipes stay readable,
and so the same pinned reference in two recipes (or in a custom one) has one entry.

To bump an engine: change the tag in the recipe (keep or drop the old @sha256:…), run with --write,
review the diff, run the tests.

Rolling tags (1.3): some projects publish images only under a tag that moves with every build
(stable-diffusion.cpp's master-vulkan, master-cuda). Their pin is the build that was checked: the
check mode reports that the tag has moved on as information (the pinned digest must still be served),
and --write keeps the pinned digest. To move one on, drop its @sha256:… (or pass --move-rolling). The digest is the multi-architecture index (or the single manifest
when the tag has no index), checked to contain linux/amd64, and linux/arm64 where the variant
claims aarch64. Only anonymous pulls are used: Docker Hub and GHCR both allow them for public images.
Every manifest and config is checked against the digest it was asked for.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from forgeyard.workloads import images as image_ids  # noqa: E402

RECIPES = ROOT / "forgeyard" / "recipes"
LOCK = image_ids.LOCK_PATH
IMAGE_LINE = re.compile(r"^(?P<lead>\s*image:\s*)(?P<image>\S+)\s*$")
ACCEPT = ", ".join([
    "application/vnd.oci.image.index.v1+json",
    "application/vnd.docker.distribution.manifest.list.v2+json",
    "application/vnd.oci.image.manifest.v1+json",
    "application/vnd.docker.distribution.manifest.v2+json",
])
INDEX_TYPES = ("application/vnd.oci.image.index.v1+json", "application/vnd.docker.distribution.manifest.list.v2+json")
LOCK_NOTE = ("Generated by scripts/pin_images.py --write; checked by scripts/pin_images.py. The ids a correct "
             "copy of each pinned image can show once loaded with docker load (forgeyard/workloads/images.py).")


def split_image(image: str) -> tuple[str, str, str, str | None]:
    """'ghcr.io/a/b:tag@sha256:x' -> ('ghcr.io', 'a/b', 'tag', 'sha256:x'); Docker Hub names get
    'registry-1.docker.io' and 'library/' for official images."""
    ref, _, digest = image.partition("@")
    name, _, tag = ref.rpartition(":") if ":" in ref.split("/")[-1] else (ref, "", "latest")
    first = name.split("/")[0]
    if "." in first or ":" in first or first == "localhost":
        registry, repo = first, name.split("/", 1)[1]
    else:
        registry, repo = "registry-1.docker.io", name if "/" in name else f"library/{name}"
    return registry, repo, tag, digest or None


class Registry:
    """Anonymous reads from one registry API (a pull token per repository, kept for the run)."""

    def __init__(self, client: httpx.Client):
        self.client = client
        self.tokens: dict[tuple[str, str], str | None] = {}

    def _token(self, registry: str, repo: str) -> str | None:
        key = (registry, repo)
        if key not in self.tokens:
            probe = self.client.get(f"https://{registry}/v2/")
            challenge = probe.headers.get("www-authenticate", "")
            token = None
            if challenge.lower().startswith("bearer"):
                params = dict(re.findall(r'(\w+)="([^"]*)"', challenge))
                realm = params.pop("realm")
                params["scope"] = f"repository:{repo}:pull"
                r = self.client.get(realm, params=params)
                r.raise_for_status()
                data = r.json()
                token = data.get("token") or data.get("access_token")
            self.tokens[key] = token
        return self.tokens[key]

    def _headers(self, registry: str, repo: str) -> dict[str, str]:
        token = self._token(registry, repo)
        return {"Accept": ACCEPT, **({"Authorization": f"Bearer {token}"} if token else {})}

    def manifest(self, registry: str, repo: str, ref: str) -> tuple[str, dict]:
        """(digest, body) of a manifest or index, by tag or digest; the bytes must hash to the digest."""
        r = self.client.get(f"https://{registry}/v2/{repo}/manifests/{ref}", headers=self._headers(registry, repo))
        r.raise_for_status()
        digest = "sha256:" + hashlib.sha256(r.content).hexdigest()
        served = r.headers.get("docker-content-digest")
        if served and served != digest:
            raise RuntimeError(f"{registry}/{repo}:{ref}: the registry says {served}, the bytes hash to {digest}")
        if ref.startswith("sha256:") and ref != digest:
            raise RuntimeError(f"{registry}/{repo}@{ref}: the bytes hash to {digest}")
        body = json.loads(r.content)
        if not body.get("mediaType"):
            body["mediaType"] = r.headers.get("content-type", "").split(";")[0]
        return digest, body

    def blob(self, registry: str, repo: str, digest: str) -> dict:
        r = self.client.get(f"https://{registry}/v2/{repo}/blobs/{digest}", headers=self._headers(registry, repo),
                            follow_redirects=True)
        r.raise_for_status()
        got = "sha256:" + hashlib.sha256(r.content).hexdigest()
        if got != digest:
            raise RuntimeError(f"{registry}/{repo} blob {digest}: the bytes hash to {got}")
        return json.loads(r.content)


ROLLING_TAG = re.compile(r"^(master|main|latest|nightly|edge)(-[a-z0-9-]+)?$")


def rolling(image: str) -> bool:
    """A tag that moves with every build (master-vulkan), as opposed to a release tag (b12242, v0.32.0)."""
    return bool(ROLLING_TAG.match(split_image(image)[2]))


def resolve(reg: Registry, image: str) -> str:
    """The digest the image's tag points at on the registry now."""
    registry, repo, tag, _ = split_image(image)
    digest, _ = reg.manifest(registry, repo, tag)
    return digest


def describe(reg: Registry, image: str) -> dict:
    """The lock entry of a pinned image (`repo:tag@sha256:…`), read from the registry by its digest:
    {"index": digest | None, "platforms": {"os/arch[/variant]": {"manifest", "config", "content"}}}.
    Attestation manifests (platform unknown/unknown) are left out: nothing runs them."""
    registry, repo, _, digest = split_image(image)
    if not digest:
        raise ValueError(f"{image} is not pinned by digest")
    _, body = reg.manifest(registry, repo, digest)
    if body["mediaType"] in INDEX_TYPES:
        index, members = digest, [(m["digest"], m.get("platform") or {}) for m in body.get("manifests", [])]
    else:
        index, members = None, [(digest, None)]
    platforms: dict[str, dict] = {}
    for mdigest, plat in members:
        if plat is not None and (not plat.get("os") or plat.get("os") == "unknown"):
            continue
        _, manifest = (reg.manifest(registry, repo, mdigest) if mdigest != digest or index else (digest, body))
        config_digest = manifest["config"]["digest"]
        config = reg.blob(registry, repo, config_digest)
        name = "/".join(x for x in (config.get("os"), config.get("architecture"), config.get("variant")) if x)
        platforms[name] = {"manifest": mdigest, "config": config_digest,
                           "content": image_ids.content_of_config(config)}
    return {"index": index, "platforms": dict(sorted(platforms.items()))}


def _wanted_platforms(text: str, line_no: int) -> set[str]:
    """linux/amd64, plus linux/arm64 when the variant this image line belongs to claims aarch64."""
    lines = text.splitlines()
    wanted = {"linux/amd64"}
    for back in range(line_no - 1, max(-1, line_no - 6), -1):
        if "when:" in lines[back]:
            if "aarch64" in lines[back]:
                wanted.add("linux/arm64")
            break
    return wanted


def read_lock(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8")).get("images") or {}
    except (OSError, ValueError):
        return {}


def write_lock(path: Path, entries: dict) -> None:
    data = {"note": LOCK_NOTE, "images": dict(sorted(entries.items()))}
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None, *, client: httpx.Client | None = None, recipes: Path = RECIPES,
         lock: Path = LOCK) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true", help="rewrite the recipes and the lock from the registry now")
    parser.add_argument("--move-rolling", action="store_true", help="with --write: also move images pinned on a "
                                                                   "rolling tag (master-vulkan) to its current build")
    args = parser.parse_args(argv)
    problems = 0
    recorded = read_lock(lock)
    entries: dict[str, dict] = {}
    own = client is None
    client = client or httpx.Client(timeout=30, follow_redirects=False)
    reg = Registry(client)
    try:
        for path in sorted(recipes.glob("*.yaml")):
            text = path.read_text(encoding="utf-8")
            out = []
            for i, line in enumerate(text.splitlines()):
                m = IMAGE_LINE.match(line)
                if not m:
                    out.append(line)
                    continue
                image = m.group("image")
                ref, _, pinned = image.partition("@")
                digest = resolve(reg, ref)
                state = "ok" if pinned == digest else ("unpinned" if not pinned else "MOVED")
                keep = bool(pinned) and state == "MOVED" and rolling(ref) and not args.move_rolling
                if keep:
                    # The tag has moved on; the pin is the build that was checked, and stays.
                    state = f"ok (rolling tag, now at {digest}; the pin stays)"
                    digest = pinned
                if not state.startswith("ok") and not args.write:
                    problems += 1
                use = f"{ref}@{digest}" if args.write or not pinned else image
                out.append(f"{m.group('lead')}{use}")
                if use not in entries:
                    entries[use] = describe(reg, use)
                entry = entries[use]
                print(f"{path.name}: {ref} -> {digest} [{', '.join(entry['platforms'])}] {state}")
                missing = _wanted_platforms(text, i) - set(entry["platforms"])
                if missing:
                    print(f"  missing platform(s): {', '.join(sorted(missing))}")
                    problems += 1
            if args.write:
                path.write_text("\n".join(out) + "\n", encoding="utf-8")
    finally:
        if own:
            client.close()
    if args.write:
        write_lock(lock, entries)
        print(f"wrote {lock.name}: {len(entries)} image(s)")
        return 1 if problems else 0
    for image, entry in entries.items():
        if image not in recorded:
            print(f"{lock.name}: no ids recorded for {image}")
            problems += 1
        elif recorded[image] != entry:
            print(f"{lock.name}: the ids recorded for {image} differ from the registry's")
            problems += 1
    for image in sorted(set(recorded) - set(entries)):
        print(f"{lock.name}: {image} is in no recipe any more")
        problems += 1
    if not problems:
        print(f"{lock.name}: the ids of all {len(entries)} image(s) match the registry")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
